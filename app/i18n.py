LANGS = ("zh", "en")
LANG_LABELS = {"zh": "中文", "en": "English"}

_current = "zh"
_listeners: list = []


def current() -> str:
    return _current


def set_lang(lang: str) -> None:
    global _current
    if lang in LANGS and lang != _current:
        _current = lang
        for cb in list(_listeners):
            cb()


def on_change(cb) -> None:
    _listeners.append(cb)


def t(key: str, *args, **kwargs) -> str:
    """取词并做 {}-占位替换；缺失时回退到中文再回退到 key 本身。"""
    table = TEXTS.get(_current, TEXTS["zh"])
    text = table.get(key) or TEXTS["zh"].get(key) or key
    if args:
        try:
            return text.format(*args)
        except Exception:
            return text
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def tag(widget, key: str):
    """给控件打上文案键，切换语言时由 retranslate() 自动重译。"""
    widget._i18n_key = key          # type: ignore[attr-defined]
    widget.configure(text=t(key))   # type: ignore[attr-defined]
    return widget


def retranslate(widget, depth: int = 0) -> int:
    """递归重译所有带 _i18n_key 标记的控件，返回更新数量。"""
    if depth > 14:
        return 0
    count = 0
    try:
        children = widget.winfo_children()
    except Exception:
        return 0
    for child in children:
        key = getattr(child, "_i18n_key", None)
        if key:
            try:
                child.configure(text=t(key))
                count += 1
            except Exception:
                pass
        count += retranslate(child, depth + 1)
    return count
